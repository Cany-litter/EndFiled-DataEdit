const currentLocale = ref<Locale>('zh-CN')

export function useI18n() {
  const t = computed(() => {
    const m = messages[currentLocale.value]
    return (key: string) => m[key] || key
  })
  return { t, currentLocale, setLocale: (l: Locale) => { currentLocale.value = l } }
}
